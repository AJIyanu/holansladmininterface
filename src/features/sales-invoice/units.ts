export function shortUnit(unit: string): string {
  return aliases[unit.trim().toLowerCase()] ?? unit.trim();
}
export function quantityNumber(quantity: string): string {
  return quantity.includes(".")
    ? quantity.replace(/0+$/, "").replace(/\.$/, "")
    : quantity;
}
export function quantityLabel(quantity: string, unit: string): string {
  return `${quantityNumber(quantity)} ${shortUnit(unit)}`;
}
